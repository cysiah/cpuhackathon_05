"""Build js/land.js: a 1-degree land mask for the globe on the project-context page.

Usage:
    python tools/build_landmask.py path/to/world-atlas/land-110m.json

land-110m.json comes from the world-atlas npm package (Natural Earth 1:110m,
public domain). The mask is 360 x 180 cells, west to east from 180 W and north
to south from 90 N, one bit per cell (1 = land), base64-encoded.
Needs Pillow.
"""
import base64
import json
import os
import sys

from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W, H = 360, 180
SCALE = 4  # draw at 4x and downsample, so thin coastlines still count


def decode_arcs(topo):
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    arcs = []
    for arc in topo["arcs"]:
        x = y = 0
        pts = []
        for dx, dy in arc:
            x += dx
            y += dy
            pts.append((x * sx + tx, y * sy + ty))
        arcs.append(pts)
    return arcs


def ring_points(ring, arcs):
    pts = []
    for i in ring:
        a = arcs[i] if i >= 0 else arcs[~i][::-1]
        pts.extend(a if not pts else a[1:])
    return pts


def unwrap(pts):
    """Make longitudes continuous across the antimeridian."""
    out = [pts[0]]
    for lon, lat in pts[1:]:
        prev = out[-1][0]
        while lon - prev > 180:
            lon -= 360
        while lon - prev < -180:
            lon += 360
        out.append((lon, lat))
    return out


def main(path):
    with open(path, encoding="utf-8") as f:
        topo = json.load(f)
    arcs = decode_arcs(topo)
    img = Image.new("L", (W * SCALE, H * SCALE), 0)
    draw = ImageDraw.Draw(img)
    to_px = lambda lon, lat: ((lon + 180) * SCALE, (90 - lat) * SCALE)

    for geom in topo["objects"]["land"]["geometries"]:
        polys = geom["arcs"] if geom["type"] == "MultiPolygon" else [geom["arcs"]]
        for poly in polys:
            for k, ring in enumerate(poly):
                pts = unwrap(ring_points(ring, arcs))
                span = pts[-1][0] - pts[0][0]
                if abs(span) > 180:
                    # ring wraps the pole (Antarctica): close it along the south edge
                    pts = pts + [(pts[-1][0], -90), (pts[0][0], -90)]
                fill = 255 if k == 0 else 0  # holes are cut out
                for shift in (-360, 0, 360):
                    draw.polygon([to_px(lon + shift, lat) for lon, lat in pts], fill=fill)

    small = img.resize((W, H), Image.BOX)
    bits = bytearray((W * H + 7) // 8)
    land = 0
    for y in range(H):
        for x in range(W):
            if small.getpixel((x, y)) >= 96:
                i = y * W + x
                bits[i >> 3] |= 1 << (i & 7)
                land += 1
    print(f"land cells: {land} of {W * H} ({100 * land / (W * H):.0f}%)")
    small.point(lambda v: 255 if v >= 96 else 0).save(os.path.join(os.path.dirname(os.path.abspath(path)), "landmask-preview.png"))

    out = os.path.join(ROOT, "js", "land.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build_landmask.py from Natural Earth 1:110m land (world-atlas). Do not edit by hand.\n")
        f.write("const LAND=" + json.dumps({"w": W, "h": H, "bits": base64.b64encode(bytes(bits)).decode("ascii")}) + ";\n")
    print("wrote", out, os.path.getsize(out), "bytes")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
