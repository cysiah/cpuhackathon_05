"""Rebuild js/data.js from the Atrium Heat Lab starter data.

Usage:
    python tools/build_data.py path/to/4_Atrium_Heat_Lab/data

Reads baseline.json, climate.json and sweep.json and writes the compact
dataset the diagrams use:
    op      atrium operative temperature, hot week (168 h), EnergyPlus baseline
    out     outdoor dry-bulb, hot week, 2050 file
    pre     outdoor dry-bulb, hot week, present-day file
    scores  EnergyPlus score x10 for all 3,125 designs, in sweep idx order
            (g, u, ach_day, ach_night, screen_opacity; 5 levels each)
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load(folder, name):
    with open(os.path.join(folder, name), encoding="utf-8") as f:
        return json.load(f)


def main(folder):
    baseline = load(folder, "baseline.json")
    climate = load(folder, "climate.json")
    sweep = load(folder, "sweep.json")

    start = climate["hot_week"]["start_hoy"]
    week = slice(start, start + 168)
    grid = sorted(sweep["grid"], key=lambda d: d["idx"])

    data = {
        "op": [round(v, 1) for v in baseline["eplus"]["operative"]],
        "out": [round(v, 1) for v in climate["dry_bulb"]["future"][week]],
        "pre": [round(v, 1) for v in climate["dry_bulb"]["present"][week]],
        "scores": [round(d["score"] * 10) for d in grid],
    }

    passing = sum(1 for s in data["scores"] if s <= 420)
    print(f"{len(grid)} designs, {passing} pass (score <= 42 K.h)")

    out_path = os.path.join(ROOT, "js", "data.js")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build_data.py from the Atrium Heat Lab starter data. Do not edit by hand.\n")
        f.write("const FF=" + json.dumps(data, separators=(",", ":")) + ";\n")
    print("wrote", out_path)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
