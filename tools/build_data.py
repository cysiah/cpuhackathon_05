"""Rebuild js/data.js from the Atrium Heat Lab starter data.

Usage:
    python tools/build_data.py path/to/4_Atrium_Heat_Lab/data

Reads baseline.json, climate.json and sweep.json and writes two files.

js/sweep.js holds every design in the sweep for the design explorer: lever
levels, scores, peaks, hours over 26/28 C, solar gain, the off-grid validation
runs and the hourly operative temperature (packed in 0.25 K steps).

js/data.js holds the compact dataset the diagrams use:
    op      atrium operative temperature, hot week (168 h), EnergyPlus baseline
    out     outdoor dry-bulb, hot week, 2050 file
    pre     outdoor dry-bulb, hot week, present-day file
    scores  EnergyPlus score x10 for all 3,125 designs, in sweep idx order
            (g, u, ach_day, ach_night, screen_opacity; 5 levels each)
"""
import base64
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load(folder, name):
    with open(os.path.join(folder, name), encoding="utf-8") as f:
        return json.load(f)


def main(folder):
    baseline = load(folder, "baseline.json")
    climate = load(folder, "climate.json")
    sweep = load(folder, "sweep.json")

    start = climate["hot_week"]["start_hoy"]
    week = slice(start, start + 168)
    grid = sorted(sweep["grid"], key=lambda d: d["idx"])

    data = {
        "op": [round(v, 1) for v in baseline["eplus"]["operative"]],
        "out": [round(v, 1) for v in climate["dry_bulb"]["future"][week]],
        "pre": [round(v, 1) for v in climate["dry_bulb"]["present"][week]],
        "scores": [round(d["score"] * 10) for d in grid],
    }

    passing = sum(1 for s in data["scores"] if s <= 420)
    print(f"{len(grid)} designs, {passing} pass (score <= 42 K.h)")
    write_js("data.js", "FF", data)

    # Full sweep for the design explorer. Hourly operative temperature is packed
    # as one byte per hour: (T - 12 C) in 0.25 K steps, base64-encoded.
    ops = bytearray()
    for d in grid:
        for t in d["operative"]:
            ops.append(max(0, min(255, round((t - OP_MIN) / OP_STEP))))
    keys = list(sweep["levers"].keys())
    explorer = {
        "keys": keys,
        "levels": [sorted(sweep["levers"][k]) for k in keys],
        "info": sweep.get("lever_info", {}),
        "base": baseline["levers"],
        "hdh": round(sum(max(0.0, 18 - t) for t in climate["dry_bulb"]["present"]), 1),
        "score": [round(d["score"], 1) for d in grid],
        "peak": [round(d["peak"], 2) for d in grid],
        "h26": [d["h26"] for d in grid],
        "h28": [d["h28"] for d in grid],
        "solar": [round(d["solar_kwh"]) for d in grid],
        "opMin": OP_MIN,
        "opStep": OP_STEP,
        "op": base64.b64encode(bytes(ops)).decode("ascii"),
        "validation": [{k: d[k] for k in keys + ["score"]} for d in sweep.get("validation", [])],
    }
    write_js("sweep.js", "SWEEP", explorer)


OP_MIN = 12.0
OP_STEP = 0.25


def write_js(name, var, obj):
    out_path = os.path.join(ROOT, "js", name)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build_data.py from the Atrium Heat Lab starter data. Do not edit by hand.\n")
        f.write("const " + var + "=" + json.dumps(obj, separators=(",", ":")) + ";\n")
    print("wrote", out_path, os.path.getsize(out_path), "bytes")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
