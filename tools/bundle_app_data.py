"""Bundle app/data/*.json into app/data/bundle.js so the app also works when index.html is opened from disk.

    python3 tools/bundle_app_data.py

Run after tools/build_real_data.py or after editing app/data/assumptions.json.
The app prefers window.FM_DATA (this bundle) and falls back to fetching the JSON files.
"""
import json
import os

D = os.path.join(os.path.dirname(__file__), "..", "app", "data")
meta = json.load(open(os.path.join(D, "meta.json")))
data = {
    "meta": meta,
    "assumptions": json.load(open(os.path.join(D, "assumptions.json"))),
    "floors": {fid: json.load(open(os.path.join(D, "floors", fid + ".json"))) for fid in meta["floors"]},
}
with open(os.path.join(D, "bundle.js"), "w") as f:
    f.write("// Generated by tools/bundle_app_data.py. Do not edit by hand.\nwindow.FM_DATA=")
    json.dump(data, f, separators=(",", ":"), ensure_ascii=False)
    f.write(";\n")
print("wrote app/data/bundle.js (%d kB)" % (os.path.getsize(os.path.join(D, "bundle.js")) // 1024))
